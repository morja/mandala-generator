    /** Vignette factor at intensity 1 for distance fraction `x` and `radius`, bilinear in the table. */
    fun vignette(x: Float, radius: Float): Float {
        val rf = ((radius - 0.40f) / 0.05f).coerceIn(0f, (vignette.size - 1).toFloat())
        val xf = (x / 0.025f).coerceIn(0f, (vignette[0].size - 1).toFloat())
        val r0 = minOf(rf.toInt(), vignette.size - 2)
        val x0 = minOf(xf.toInt(), vignette[0].size - 2)
        val fr = rf - r0
        val fx = xf - x0
        val a = vignette[r0][x0] + (vignette[r0][x0 + 1] - vignette[r0][x0]) * fx
        val b = vignette[r0 + 1][x0] + (vignette[r0 + 1][x0 + 1] - vignette[r0 + 1][x0]) * fx
        return a + (b - a) * fr
    }

    fun sepia(table: FloatArray, luma: Float): Float {
        val p = luma.coerceIn(0f, 1f) * (table.size - 1)
        val i = minOf(p.toInt(), table.size - 2)
        return table[i] + (table[i + 1] - table[i]) * (p - i)
    }
